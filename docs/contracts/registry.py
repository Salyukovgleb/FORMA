def group(route):
    if route.startswith("/health"):
        return "system"
    if "/auth/" in route or "/users/me" in route:
        return "identity"
    if "/members" in route:
        return "access"
    if any(s in route for s in ["/compilations", "/exports"]):
        return "documents"
    if "/jobs" in route or "/artifacts/" in route:
        return "jobs"
    if any(s in route for s in ["/tree", "/folders", "/files", "/nodes", "/uploads"]):
        return "project-files"
    return "projects"
