from pathlib import Path
from uuid import uuid4

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, select, text

from forma_backend.infrastructure.database.models import User
from forma_backend.infrastructure.database.session import create_database_engine, unit_of_work

ROOT = Path(__file__).resolve().parents[2]


def config(connection):
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.attributes["connection"] = connection
    return cfg


def test_fresh_upgrade_and_schema_drift(database_url):
    engine = create_database_engine(database_url)
    try:
        with engine.begin() as conn:
            cfg = config(conn)
            command.upgrade(cfg, "head")
            assert set(inspect(conn).get_table_names()) == {
                "users",
                "auth_sessions",
                "used_refresh_tokens",
                "rate_limit_buckets",
                "alembic_version",
            }
            command.check(cfg)
            conn.execute(text("ALTER TABLE users ADD COLUMN accidental text"))
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(cfg)
    finally:
        engine.dispose()


def test_seeded_upgrade_and_safe_disposable_roundtrip(database_url, monkeypatch):
    engine = create_database_engine(database_url)
    monkeypatch.setenv("FORMA_ALLOW_DESTRUCTIVE_DOWNGRADE", "1")
    try:
        with engine.begin() as conn:
            cfg = config(conn)
            command.upgrade(cfg, "0001_users")
            conn.execute(
                text(
                    "INSERT INTO users(id,email,password_hash,display_name) VALUES (:id,'owner@example.org','fixture','Owner')"
                ),
                {"id": uuid4()},
            )
            command.upgrade(cfg, "head")
            command.upgrade(cfg, "head")
            assert conn.scalar(text("SELECT count(*) FROM users")) == 1
            command.downgrade(cfg, "0001_users")
            assert conn.scalar(text("SELECT count(*) FROM users")) == 1
            command.upgrade(cfg, "head")
            command.check(cfg)
            with pytest.raises(RuntimeError, match="downgrade"):
                monkeypatch.delenv("FORMA_ALLOW_DESTRUCTIVE_DOWNGRADE")
                command.downgrade(cfg, "base")
            monkeypatch.setenv("FORMA_ALLOW_DESTRUCTIVE_DOWNGRADE", "1")
            command.downgrade(cfg, "base")
            assert set(inspect(conn).get_table_names()) == {"alembic_version"}
            command.upgrade(cfg, "head")
            command.check(cfg)
    finally:
        engine.dispose()


def test_unit_of_work_requires_explicit_commit(database_url):
    engine = create_database_engine(database_url)
    try:
        with engine.begin() as conn:
            command.upgrade(config(conn), "head")
        with unit_of_work(engine) as session:
            session.add(
                User(
                    id=uuid4(),
                    email="rolled@example.org",
                    password_hash="fixture",
                    display_name="Rollback",
                )
            )
        with unit_of_work(engine) as session:
            assert session.scalar(select(User)) is None
            session.add(
                User(
                    id=uuid4(),
                    email="kept@example.org",
                    password_hash="fixture",
                    display_name="Commit",
                )
            )
            session.commit()
        with pytest.raises(RuntimeError):
            with unit_of_work(engine) as session:
                session.add(
                    User(
                        id=uuid4(),
                        email="error@example.org",
                        password_hash="fixture",
                        display_name="Error",
                    )
                )
                session.flush()
                raise RuntimeError("abort")
        with unit_of_work(engine) as session:
            assert [u.email for u in session.scalars(select(User))] == ["kept@example.org"]
    finally:
        engine.dispose()


def test_cli_upgrade_and_database_constraints(database_url):
    import os
    import subprocess
    import sys
    from sqlalchemy.exc import IntegrityError

    env = {**os.environ, "DATABASE_URL": database_url.render_as_string(hide_password=False)}
    result = subprocess.run(
        [sys.executable, "-m", "alembic", "upgrade", "head"],
        cwd=ROOT,
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, "CLI migration failed"
    engine = create_database_engine(database_url)
    try:
        for sql in [
            "INSERT INTO users(id,email,password_hash,display_name) VALUES (gen_random_uuid(),'UPPER@example.org','fixture','User')",
            "INSERT INTO rate_limit_buckets VALUES ('login',repeat('a',64),now(),-1)",
            "INSERT INTO auth_sessions(id,user_id,refresh_token_hash,csrf_token_hash,expires_at) VALUES(gen_random_uuid(),gen_random_uuid(),repeat('a',64),repeat('b',64),now()+interval '1 day')",
        ]:
            with pytest.raises(IntegrityError):
                with engine.begin() as conn:
                    conn.execute(text(sql))
        with engine.begin() as conn:
            command.check(config(conn))
    finally:
        engine.dispose()
